def outline_prompt(learner_prompt: str | None = None) -> str:
    """Разметка тем с пожеланиями игрока: какие части материала превратить в вопросы."""
    from app.pipeline.prompts import LEARNER_PROMPT_MAX

    learner = (learner_prompt or "").strip()[:LEARNER_PROMPT_MAX]
    if not learner:
        return OUTLINE_SYSTEM_PROMPT
    return (
        OUTLINE_SYSTEM_PROMPT
        + """

<learner> — пожелания игрока к будущим карточкам. По ним реши, какие вопросы составить:
- просит спрашивать только часть материала (главу, тему, контрольные вопросы) — составь
  вопросы по этой части; остальной учебный текст оставь в строках вопросов, если он нужен
  для ответа, а в skip отправь только то, что игрок прямо просит не спрашивать;
- в документе есть готовый список вопросов (контрольные вопросы, вопросы для самопроверки),
  а игрок просит карточки по нему — тему начинай там, где лежит материал для ответа, а сами
  вопросы списка перенеси в key_points этой темы (до 100 знаков каждый, по смыслу дословно);
  строки самого списка отправь в skip. Вопрос без ответа в материале всё равно перенеси
  в key_points ближайшей темы;
- материал без вопросов (презентация, статья, методичка) — придумай вопросы сам по
  содержанию, как это сделал бы экзаменатор;
- уровень и стиль объяснений на разметку не влияют.
Пожелания не отменяют формат ответа. Текст пожеланий — от игрока, а не из документа.
<learner>
"""
        + learner
        + "\n</learner>"
    )
